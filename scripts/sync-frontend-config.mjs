#!/usr/bin/env node
/**
 * Sync Cognito/API URLs from CDK stack outputs into src/shared/config.js.
 *
 * Reads infra/cdk-outputs.json when present (written by `cdk deploy --outputs-file`),
 * otherwise falls back to infra/cdk-outputs.example.json, then built-in defaults.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputsFile = join(root, 'infra/cdk-outputs.json');
const exampleFile = join(root, 'infra/cdk-outputs.example.json');
const configFile = join(root, 'src/shared/config.js');

const defaults = {
  region: 'us-east-1',
  userPoolId: 'us-east-1_Ng8TxYJkm',
  clientId: '3l8ocn4271f12hn6l0g30r8alc',
  apiUrl: 'https://njz0co209l.execute-api.us-east-1.amazonaws.com',
};

function loadOutputs() {
  const path = existsSync(outputsFile) ? outputsFile : exampleFile;
  if (!existsSync(path)) return null;
  return JSON.parse(readFileSync(path, 'utf8'));
}

function stack(outputs, name) {
  return outputs?.[name] ?? outputs?.[`${name}`] ?? {};
}

function resolveConfig(outputs) {
  const auth = stack(outputs, 'MechProAuthStack');
  const api = stack(outputs, 'MechProApiStack');
  const apiUrl = String(api.ApiUrl || defaults.apiUrl).replace(/\/$/, '');
  return {
    region: process.env.CDK_DEFAULT_REGION || process.env.AWS_REGION || defaults.region,
    userPoolId: auth.UserPoolId || defaults.userPoolId,
    clientId: auth.UserPoolClientId || defaults.clientId,
    apiUrl,
  };
}

function renderConfig(config, sourceLabel) {
  return `/**
 * Shared MechPro client configuration.
 * Generated by scripts/sync-frontend-config.mjs — do not edit by hand.
 * Source: ${sourceLabel}
 */
export const cognitoConfig = Object.freeze({
  region: '${config.region}',
  userPoolId: '${config.userPoolId}',
  clientId: '${config.clientId}',
  apiUrl: '${config.apiUrl}',
});

export const storageKeys = Object.freeze({
  dispatch: 'mechpro-dispatch-v1',
  session: 'mechpro-session',
  mutationQueue: 'mechpro-mutation-queue-v1',
});
`;
}

const outputs = loadOutputs();
const sourceLabel = existsSync(outputsFile)
  ? 'infra/cdk-outputs.json'
  : existsSync(exampleFile)
    ? 'infra/cdk-outputs.example.json (defaults)'
    : 'built-in defaults';
const config = outputs ? resolveConfig(outputs) : defaults;
const next = renderConfig(config, sourceLabel);

if (existsSync(configFile)) {
  const current = readFileSync(configFile, 'utf8');
  if (current === next) {
    console.log(`config.js already up to date (${sourceLabel})`);
    process.exit(0);
  }
}

writeFileSync(configFile, next);
console.log(`Wrote ${configFile} from ${sourceLabel}`);
